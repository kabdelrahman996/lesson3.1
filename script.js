function step() {
  const S = SC().S;
  if (st >= S.length || fail) return;
  if (!q) {
    q = SC().ph;
    $('#q').value = q;
  }
  const [t, l, r, c, k, sq, a] = S[st], el = $(`.stn[data-l=${t}]`);
  $$('.stn').forEach(x => x.classList.remove('act', 'bad'));
  if (off[t]) {
    fail = 1;
    el.classList.add('bad');
    mvp(t, l, r, 1);
    cap('⛔ ' + FM[t][0], 1);
    $('#res').innerHTML = FM[t][1];
    if (t == 'f') $('#scr').classList.add('dead');
    return;
  }
  st++;
  el.classList.add('act');
  if (window.matchMedia('(max-width: 820px)').matches) {
    el.scrollIntoView({ behavior: 'smooth', block: 'nearest', inline: 'center' });
  }
  mvp(t, l, r);
  cap(c);
  chk(k);
  if (sq) $('#sq').textContent = SC().sql(q);
  if (a == 'scan') scan();
  if (a == 'ins') {
    R.push(SC().row(q, R.length));
    rdb();
  }
  if (a == 'show') $('#res').innerHTML = SC().show(q, hits());
}

